"""The "No conversation links" check (.github/scripts/check_conversation_links.py).

A pull request whose title, description or commit messages link to a
private claude.ai page must fail; ordinary text and generic product links
must pass; and the check's own output must never repeat the link, since
the logs of a public repository's Actions runs are public too.

The links below are made up, in the same shape as real ones.

Run: python3 tests/conversation_links_test.py
"""
from __future__ import annotations

import sys as _sys_path
from pathlib import Path as _Path

# Run against THIS checkout, never an installed copy of Ensign.
ROOT = _Path(__file__).resolve().parent.parent
_sys_path.path.insert(0, str(ROOT))

import importlib.util  # noqa: E402
import json  # noqa: E402
import os  # noqa: E402
import subprocess  # noqa: E402
import sys  # noqa: E402
import tempfile  # noqa: E402

SCRIPT = ROOT / ".github" / "scripts" / "check_conversation_links.py"
spec = importlib.util.spec_from_file_location("check_conversation_links", SCRIPT)
check = importlib.util.module_from_spec(spec)
spec.loader.exec_module(check)

SESSION_ID = "session_01EXAMPLEexample0Example"
SESSION_URL = f"https://claude.ai/code/{SESSION_ID}"

# --- what counts as a link ---------------------------------------------------
flagged = [
    SESSION_URL,
    f"See ({SESSION_URL}) for the discussion",
    "https://claude.ai/chat/0f3c2b1a-1111-2222-3333-444455556666",
    "https://claude.ai/share/0f3c2b1a-1111-2222-3333-444455556666",
    "https://claude.ai/project/019e0000-0000-7000-8000-000000000000",
    "https://claude.ai/artifact/AbCdEfGhIjKlMnOpQrStUv",
    "https://claude.ai/code/artifact/AbCdEfGhIjKlMnOpQrStUv",
    "https://CLAUDE.AI/Chat/abc",                       # case doesn't hide it
    f"id only: {SESSION_ID}",                           # the id without the URL
    "Fix a thing\n\nClaude-Session: https://example.invalid/x",  # the trailer itself
]
for text in flagged:
    assert check.lines_with_links(text), f"not flagged: {text!r}"

allowed = [
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "_Generated by [Claude Code](https://claude.ai/code)_",  # generic, no session
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "Each session stores its own ctime; session handling is unchanged.",
    "See https://github.com/WolfdeerNerd/ensign-scan/pull/43",
    "",
    None,
]
for text in allowed:
    assert not check.lines_with_links(text), f"wrongly flagged: {text!r}"

# Line numbers point at the right place.
assert check.lines_with_links(f"one\ntwo\n{SESSION_URL}\nfour\n{SESSION_URL}") == [3, 5]

# --- where it looks ----------------------------------------------------------
page1 = [{"sha": "a" * 40, "commit": {"message": "Clean commit\n\nCo-Authored-By: Claude <noreply@anthropic.com>"}}]
page2 = [{"sha": "b" * 40, "commit": {"message": f"Dirty commit\n\nClaude-Session: {SESSION_URL}"}}]
found = check.findings("A fine title", f"Body\n\n{SESSION_URL}", page1 + page2)
assert found == ["PR description, line 3", "commit bbbbbbbbbbbb, message line 3"], found
assert check.findings(f"Title {SESSION_URL}", "", []) == ["PR title"]
assert check.findings("Title", "Body", page1) == []


# --- the script as CI runs it ------------------------------------------------
def run(title: str, body: str | None, pages: list) -> subprocess.CompletedProcess:
    with tempfile.TemporaryDirectory() as d:
        pr, commits = os.path.join(d, "pr.json"), os.path.join(d, "commits.json")
        with open(pr, "w", encoding="utf-8") as f:
            json.dump({"number": 1, "title": title, "body": body}, f)
        with open(commits, "w", encoding="utf-8") as f:
            json.dump(pages, f)  # pages of commits, as gh api --paginate --slurp writes them
        # A link in the environment would be printed in the public log by
        # the runner itself: the script must not need one there.
        env = {k: v for k, v in os.environ.items() if k not in ("PR_TITLE", "PR_BODY")}
        return subprocess.run([sys.executable, str(SCRIPT), pr, commits], env=env,
                              capture_output=True, text=True, timeout=30, check=False)


clean = run("Fix a bug", "## The bug\n\nDetails.", [page1])
assert clean.returncode == 0, clean.stdout + clean.stderr

dirty = run("Fix a bug", f"Details.\n\n{SESSION_URL}", [page1, page2])
assert dirty.returncode == 1, dirty.stdout + dirty.stderr
assert "PR description, line 3" in dirty.stdout and "commit bbbbbbbbbbbb" in dirty.stdout
# The log names the place, never the link: Actions logs are public.
assert SESSION_ID not in dirty.stdout + dirty.stderr, "the check printed the link"

# A description someone left empty is fine (GitHub sends null).
assert run("Title", None, [[]]).returncode == 0

print("conversation-link check tests passed")
